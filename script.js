function findBin(){

const searchInput = document.getElementById("searchInput");
const result = document.getElementById("result");

let input = searchInput.value.toLowerCase().trim();

result.style.display="block";

clearHighlights();

if(wasteDatabase[input]){

const item = wasteDatabase[input];

result.style.background = "#f8f9fa";
result.style.borderLeft = `4px solid ${item.color}`;
result.style.padding = "15px";
result.style.borderRadius = "8px";

result.innerHTML = `
<div style="margin-bottom: 8px;">
<strong style="font-size: 1.2rem; color: ${item.color};">${input.toUpperCase()}</strong>
</div>
<div style="margin-bottom: 8px;">
<i class="fas fa-trash-alt"></i> <strong>Bin:</strong> ${item.category}
</div>
<div>
<i class="fas fa-info-circle"></i> <strong>Why:</strong> ${item.description}
</div>
`;

highlightCategory(input);

}

else{

result.style.background = "#f8f9fa";
result.style.borderLeft = "4px solid #c0392b";
result.style.padding = "15px";
result.style.borderRadius = "8px";
result.style.color = "#c0392b";

result.innerHTML = `
<div style="margin-bottom: 8px;">
<i class="fas fa-exclamation-triangle"></i> <strong>Item not found!</strong>
</div>
<div>
Try searching things like <em>apple, plastic bottle, battery, diaper</em>
</div>
`;

}

}


const inputBox = document.getElementById("searchInput");
const suggestions = document.getElementById("suggestions");

const items = Object.keys(wasteDatabase);

inputBox.addEventListener("input", function(){

let value = inputBox.value.toLowerCase();

suggestions.innerHTML = "";

if(value.length === 0) return;

let filtered = items.filter(item => item.includes(value));

filtered = filtered.slice(0, 8);

filtered.forEach(item => {

let div = document.createElement("div");

div.classList.add("suggestion-item");

const color = wasteDatabase[item].color;
div.innerHTML = `<span style="display:inline-block;width:8px;height:8px;background:${color};border-radius:50%;margin-right:8px;"></span>${item}`;

div.onclick = function(){

inputBox.value = item;

suggestions.innerHTML = "";

};

suggestions.appendChild(div);

});

});



inputBox.addEventListener("keypress", function(e){

if(e.key === "Enter"){

findBin();

}

});



function toggleAbout() {
    const aboutSection = document.getElementById("aboutSection");
    aboutSection.classList.toggle("show");
}


function clearHighlights() {
    const cards = document.querySelectorAll('.card');
    cards.forEach(card => {
        card.classList.remove('highlight');
        card.classList.remove('dimmed');
    });
}

function highlightCategory(input) {
    if (!wasteDatabase[input]) return;
    
    const item = wasteDatabase[input];
    const category = item.category;
    
    let categoryClass = '';
    if (category.includes('Organic')) {
        categoryClass = 'organic';
    } else if (category.includes('Recyclable')) {
        categoryClass = 'recyclable';
    } else if (category.includes('Hazardous')) {
        categoryClass = 'hazardous';
    } else if (category.includes('Residual')) {
        categoryClass = 'residual';
    }
    
    const cards = document.querySelectorAll('.card');
    cards.forEach(card => {
        if (card.classList.contains(categoryClass)) {
            card.classList.add('highlight');
        } else {
            card.classList.add('dimmed');
        }
    });
    
    const guideSection = document.getElementById('guide');
    if (guideSection) {
        setTimeout(() => {
            guideSection.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }, 300);
    }
}
